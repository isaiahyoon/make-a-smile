const languageNames = { en: "EN", es: "ES", ko: "KO" };
const languageToggle = document.querySelector("#language-toggle");
const languageMenu = document.querySelector("#language-menu");
const languageCode = document.querySelector("#language-code");
const navigationToggle = document.querySelector(".nav-toggle");
const navigation = document.querySelector("#primary-navigation");
const galleryDialog = document.querySelector("#gallery-lightbox");
const lightboxImage = document.querySelector("#lightbox-image");
const lightboxCaption = document.querySelector("#lightbox-caption");
const galleryButtons = [...document.querySelectorAll(".gallery-open")];
let currentLanguage = "en";
let currentPhoto = 0;

function languageFromUrl() {
  const language = new URLSearchParams(window.location.search).get("lang");
  return copy[language] ? language : "en";
}

function updateLanguageUrl(language) {
  const url = new URL(window.location.href);
  if (language === "en") {
    url.searchParams.delete("lang");
  } else {
    url.searchParams.set("lang", language);
  }
  if (url.href !== window.location.href) {
    window.history.pushState({ language }, "", url);
  }
}

function setLanguage(language, updateUrl = true) {
  if (!copy[language]) return;

  if (updateUrl) updateLanguageUrl(language);
  currentLanguage = language;
  document.documentElement.lang = language;
  document.title = copy[language].pageTitle;
  document.querySelector("[data-meta-description]").content = copy[language].pageDescription;
  languageCode.textContent = languageNames[language];

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());
    const value = copy[language][key];
    if (value) element.textContent = value;
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const key = element.dataset.i18nAlt.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());
    const value = copy[language][key];
    if (value) element.alt = value;
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const key = element.dataset.i18nAria.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());
    const value = copy[language][key];
    if (value) element.setAttribute("aria-label", value);
  });
  const filmFrame = document.querySelector("#film-frame");
  if (filmFrame) filmFrame.title = copy[language].filmTitleAccessible;
  navigationToggle.setAttribute(
    "aria-label",
    copy[language][navigationToggle.getAttribute("aria-expanded") === "true" ? "menuClose" : "menuOpen"],
  );

  languageMenu.querySelectorAll("[data-language]").forEach((button) => {
    button.setAttribute("aria-checked", String(button.dataset.language === language));
  });

  if (galleryDialog.open) updateLightbox();
}

function setLanguageMenu(open) {
  languageMenu.hidden = !open;
  languageToggle.setAttribute("aria-expanded", String(open));
  if (open) {
    languageMenu.querySelector(`[data-language="${currentLanguage}"]`).focus();
  }
}

languageToggle.addEventListener("click", () => {
  setLanguageMenu(languageMenu.hidden);
});

languageMenu.addEventListener("click", (event) => {
  const button = event.target.closest("[data-language]");
  if (!button) return;
  setLanguage(button.dataset.language);
  setLanguageMenu(false);
  languageToggle.focus();
});

languageMenu.addEventListener("keydown", (event) => {
  const options = [...languageMenu.querySelectorAll("[data-language]")];
  const currentIndex = options.indexOf(document.activeElement);
  let nextIndex;

  if (event.key === "ArrowDown") nextIndex = (currentIndex + 1) % options.length;
  if (event.key === "ArrowUp") nextIndex = (currentIndex - 1 + options.length) % options.length;
  if (event.key === "Home") nextIndex = 0;
  if (event.key === "End") nextIndex = options.length - 1;
  if (nextIndex === undefined) return;

  event.preventDefault();
  options[nextIndex].focus();
});

document.addEventListener("click", (event) => {
  if (!event.target.closest(".language-control") && !languageMenu.hidden) {
    setLanguageMenu(false);
  }
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape" && !languageMenu.hidden) {
    setLanguageMenu(false);
    languageToggle.focus();
  }
});

navigationToggle.addEventListener("click", () => {
  const open = navigationToggle.getAttribute("aria-expanded") !== "true";
  navigationToggle.setAttribute("aria-expanded", String(open));
  navigationToggle.setAttribute("aria-label", copy[currentLanguage][open ? "menuClose" : "menuOpen"]);
  navigation.classList.toggle("is-open", open);
  navigationToggle.classList.toggle("is-open", open);
});

navigation.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => {
    navigation.classList.remove("is-open");
    navigationToggle.classList.remove("is-open");
    navigationToggle.setAttribute("aria-expanded", "false");
    navigationToggle.setAttribute("aria-label", copy[currentLanguage].menuOpen);
  });
});

const filmLaunch = document.querySelector("#film-launch");
filmLaunch.addEventListener("click", () => {
  const frame = document.createElement("iframe");
  frame.id = "film-frame";
  frame.src = "https://www.youtube-nocookie.com/embed/kHAXeYi1O4Y?autoplay=1&rel=0";
  frame.title = copy[currentLanguage].filmTitleAccessible;
  frame.allow = "accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture";
  frame.referrerPolicy = "strict-origin-when-cross-origin";
  frame.allowFullscreen = true;
  frame.loading = "lazy";
  filmLaunch.replaceWith(frame);
});

function updateLightbox() {
  const selected = galleryButtons[currentPhoto];
  const image = selected.querySelector("img");
  const caption = selected.closest("figure").querySelector("figcaption");
  lightboxImage.src = image.src;
  lightboxImage.alt = image.alt;
  lightboxCaption.textContent = caption.textContent;
}

function changePhoto(direction) {
  currentPhoto = (currentPhoto + direction + galleryButtons.length) % galleryButtons.length;
  updateLightbox();
}

galleryButtons.forEach((button) => {
  button.addEventListener("click", () => {
    currentPhoto = Number(button.dataset.galleryIndex);
    updateLightbox();
    galleryDialog.showModal();
  });
});

document.querySelector("#lightbox-close").addEventListener("click", () => galleryDialog.close());
document.querySelector("#lightbox-prev").addEventListener("click", () => changePhoto(-1));
document.querySelector("#lightbox-next").addEventListener("click", () => changePhoto(1));

galleryDialog.addEventListener("click", (event) => {
  if (event.target === galleryDialog) galleryDialog.close();
});

galleryDialog.addEventListener("keydown", (event) => {
  if (event.key === "Escape") {
    event.preventDefault();
    galleryDialog.close();
  }
  if (event.key === "ArrowLeft") changePhoto(-1);
  if (event.key === "ArrowRight") changePhoto(1);
});

